#!/usr/bin/env node
/**
 * Regenerates app/lib/vehicleIndexAllowlist.ts — the vehicle pages that must
 * NEVER be noindexed because they already earn search impressions.
 *
 * Inputs (any combination, at least one):
 *   --gsc  <file>  JSON output of the Search Console searchAnalytics/query call
 *                  with dimensions ["page"] (rows[].keys[0] = URL)
 *   --bing <file>  Bing Webmaster Tools "Page Traffic" CSV export ("Page" column first)
 *
 * Example:
 *   node ~/.config/mpgcalculator/gsc.mjs POST /webmasters/v3/sites/sc-domain%3Ampgcalculator.net/searchAnalytics/query \
 *     '{"startDate":"2025-08-01","endDate":"2026-11-24","dimensions":["page"],"rowLimit":25000}' > /tmp/gsc.json
 *   node scripts/build-vehicle-index-allowlist.mjs --gsc /tmp/gsc.json --bing public/mpgcalculator.net_PageTrafficReport_6_27_2026.csv
 *
 * The list only ever grows: existing entries are kept so a page never flips
 * back to noindex just because it fell out of the reporting window.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.join(__dirname, '../app/lib/vehicleIndexAllowlist.ts')

const args = process.argv.slice(2)
const getArg = (name) => {
  const i = args.indexOf(name)
  return i === -1 ? null : args[i + 1]
}

function slugFromUrl(url) {
  const m = /\/vehicles\/([^/?#]+)/.exec(url)
  if (!m) return null
  const slug = decodeURIComponent(m[1]).toLowerCase()
  return /^\d{4}-.+-mpg$/.test(slug) ? slug : null
}

const slugs = new Set()

// Keep what is already there (append-only)
if (fs.existsSync(OUT)) {
  for (const m of fs.readFileSync(OUT, 'utf8').matchAll(/^\s+'([^']+)',$/gm)) slugs.add(m[1])
}
const before = slugs.size

const gscFile = getArg('--gsc')
if (gscFile) {
  const rows = JSON.parse(fs.readFileSync(gscFile, 'utf8')).rows || []
  for (const r of rows) {
    const s = slugFromUrl(r.keys[0])
    if (s && r.impressions > 0) slugs.add(s)
  }
}

const bingFile = getArg('--bing')
if (bingFile) {
  const lines = fs.readFileSync(bingFile, 'utf8').split(/\r?\n/).slice(1)
  for (const line of lines) {
    const cells = line.match(/"([^"]*)"/g)?.map((c) => c.slice(1, -1))
    if (!cells) continue
    const s = slugFromUrl(cells[0])
    if (s && Number(cells[1]) > 0) slugs.add(s)
  }
}

if (!gscFile && !bingFile) {
  console.error('Pass --gsc <file> and/or --bing <file>')
  process.exit(1)
}

const sorted = [...slugs].sort()
const body = `// AUTO-GENERATED by scripts/build-vehicle-index-allowlist.mjs — do not edit by hand.
// Vehicle pages that already earned Google (Search Console) or Bing impressions.
// These stay indexable (self-canonical, in the sitemap) no matter what the keeper rule says.
// Append-only: re-running the script never removes entries.
// Last generated: ${new Date().toISOString().slice(0, 10)} (${sorted.length} slugs)

export const VEHICLE_INDEX_ALLOWLIST: ReadonlySet<string> = new Set([
${sorted.map((s) => `  '${s.replace(/'/g, "\\'")}',`).join('\n')}
])
`
fs.writeFileSync(OUT, body)
console.log(`Wrote ${OUT}: ${sorted.length} slugs (${sorted.length - before} new)`)
